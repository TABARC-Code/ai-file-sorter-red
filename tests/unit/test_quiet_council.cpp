SessionMetrics healthy() {
    SessionMetrics m;
    for (const auto& r : researchers()) {
        m.researchers.push_back({r.name, true, 5});
    }
    m.tier1 = 10;
    m.tier2 = 10;
    m.tier3 = 4;
    m.tier4 = 1;
    m.contradictions_found = 3;
    m.gaps = 3;
    m.gaps_with_followup = 3;
    return m;
}

std::vector<std::string> types_of(const std::vector<Flag>& flags) {
    std::vector<std::string> out;
    for (const auto& f : flags) {
        out.push_back(f.type);
    }
    return out;
}

