fs::path scratch(const std::string& name) {
    const fs::path dir = fs::temp_directory_path() / ("qc_test_" + name);
    fs::remove_all(dir);
    fs::create_directories(dir);
    return dir;
}

std::string slurp(const fs::path& path) {
    std::ifstream in(path, std::ios::binary);
    std::stringstream ss;
    ss << in.rdbuf();
    return ss.str();
}

